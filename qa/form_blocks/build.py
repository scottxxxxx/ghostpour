#!/usr/bin/env python3
"""Writes the served FORM BLOCK config for each vendored form definition.

form_block.py and the form_definition_*.json files here are vendored from
the I-765 app repo (I765Helper/Scripts/form_block.py and
I765Helper/Sources/Resources/MockFixtures/) at the commit named in
README.md. Never edit them by hand: re-vendor and run this.

    python3 qa/form_blocks/build.py

For each definition it writes config/remote/i765/form-block-<code>.json with
the definition's sha256 and git blob, and the block with the generator's two
HTML comment lines removed, since they are for people and the model never
needs them. tests/test_form_interviewer_lane.py pins served block ==
generator(vendored definition) and the vendored sha256 == the pin, so a
definition that moves without a rebuild goes red.
"""
import hashlib
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT_DIR = os.path.join(ROOT, "config", "remote", "i765")

# The forms served on the generic lane. The I-765 is not here: it stays on
# i765/interviewer-turn until a parity run moves it.
SERVED = ["form_definition_i131.json"]


def _generator():
    spec = importlib.util.spec_from_file_location("form_block", os.path.join(HERE, "form_block.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def served_block(definition_path: str) -> str:
    text = _generator().form_block(definition_path)
    lines = text.split("\n")
    while lines and (lines[0].startswith("<!--") or not lines[0].strip()):
        lines.pop(0)
    return "\n".join(lines).rstrip("\n")


def block_config(definition_path: str, previous: dict | None) -> dict:
    with open(definition_path, "rb") as fh:
        data = fh.read()
    definition = json.loads(data)
    block = served_block(definition_path)
    version = (previous or {}).get("version", 0)
    if (previous or {}).get("block") != block:
        version += 1
    return {
        "version": version,
        "server_only": True,
        "_comment": [
            f"FORM BLOCK for Form {definition['form_code']} on form_interviewer_turn.",
            "GENERATED by qa/form_blocks/build.py from the vendored definition;",
            "never edit by hand. GP appends `block` after i765/interviewer-lane.",
        ],
        "form_code": definition["form_code"],
        "definition": os.path.basename(definition_path),
        "definition_sha256": hashlib.sha256(data).hexdigest(),
        "definition_git_blob": hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest(),
        "block": block,
    }


def main() -> None:
    for name in SERVED:
        path = os.path.join(HERE, name)
        code = json.load(open(path, encoding="utf-8"))["form_code"].replace("-", "").lower()
        out = os.path.join(OUT_DIR, f"form-block-{code}.json")
        previous = json.load(open(out, encoding="utf-8")) if os.path.exists(out) else None
        cfg = block_config(path, previous)
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(cfg, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(out, "version", cfg["version"], "words", len(cfg["block"].split()), "sha256", cfg["definition_sha256"])


if __name__ == "__main__":
    sys.exit(main())
